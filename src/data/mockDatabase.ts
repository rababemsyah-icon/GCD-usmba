export function calculateUsbaMeritScore(
  masterAverage: number,
  mention: string,
  diplomaFieldMatchRatio: number = 0.95,
  yearsWithoutRepeating: boolean = true
): number {
  const masterComponent = (Math.min(20, Math.max(10, masterAverage)) / 20) * 50;
  let mentionBonus = 8;
  if (mention.toLowerCase().includes('très bien') || masterAverage >= 16) mentionBonus = 15;
  else if (mention.toLowerCase().includes('bien') || masterAverage >= 14) mentionBonus = 12;
  else if (mention.toLowerCase().includes('assez bien') || masterAverage >= 12) mentionBonus = 9;

  const matchComponent = diplomaFieldMatchRatio * 25;
  const regularityBonus = yearsWithoutRepeating ? 10 : 5;

  const totalScore = masterComponent + mentionBonus + matchComponent + regularityBonus;
  return Math.min(100, Math.round(totalScore * 10) / 10);
}
